interface SpecialtyProductDraft {
  readonly id: string;
  readonly slug: string;
  readonly title: string;
  readonly brand: string;
  readonly searchTags: readonly string[];
  readonly image: string;
  readonly priceCents: number;
  readonly listPriceCents: number;
  readonly rating: number;
  readonly reviewCount: number;
  readonly boughtPastMonth: number;
  readonly prime: boolean;
  readonly delivery: Product['delivery'];
  readonly badges: readonly Product['badges'][number][];
  readonly features: readonly string[];
  readonly specifications: Readonly<Record<string, string>>;
  readonly variantName: Product['variants'][number]['name'];
  readonly variantValue: string;
}

function makeSpecialtyProduct(draft: SpecialtyProductDraft): Product {
  return {
    id: draft.id,
    slug: draft.slug,
    title: draft.title,
    brand: draft.brand,
    category: 'specialty',
    searchTags: draft.searchTags,
    images: [draft.image],
    priceCents: draft.priceCents,
    listPriceCents: draft.listPriceCents,
    rating: draft.rating,
    reviewCount: draft.reviewCount,
    boughtPastMonth: draft.boughtPastMonth,
    prime: draft.prime,
    delivery: draft.delivery,
    stock: { status: 'in-stock', message: 'In Stock' },
    badges: draft.badges,
    features: draft.features,
    specifications: draft.specifications,
    variants: [
      {
        id: 'standard',
        name: draft.variantName,
        value: draft.variantValue,
        inStock: true,
      },
    ],
  };
}

